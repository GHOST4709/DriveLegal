"""
schemas.py
----------
Pydantic v2 models used for:
  1. FastAPI request/response validation  (TrafficLawBase, TrafficLawResponse)
  2. LangChain structured output parsing  (ChatbotExtraction)
  3. Chat endpoint payloads               (ChatRequest, ChatResponse)
"""

from typing import Literal
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# FastAPI response schemas
# ---------------------------------------------------------------------------

class TrafficLawBase(BaseModel):
    """
    Shared fields mirroring the TrafficLaw ORM model.
    Used as the foundation for all traffic-law API responses.
    """

    country: str = Field(
        ...,
        description="Country where the law is applicable.",
        examples=["Bangladesh", "Thailand"],
    )
    city: str = Field(
        ...,
        description="City where the law is applicable.",
        examples=["Dhaka", "Bangkok"],
    )
    violation_name: str = Field(
        ...,
        description="Human-readable name of the traffic violation.",
        examples=["Speeding", "Red Light", "No Helmet"],
    )
    vehicle_type: str = Field(
        ...,
        description="Category of vehicle: 'Two-Wheeler' or 'Four-Wheeler'.",
        examples=["Two-Wheeler", "Four-Wheeler"],
    )
    fine_amount: int = Field(
        ...,
        description="Monetary penalty for this violation.",
        examples=[500, 1000, 2000],
    )
    currency: str = Field(
        ...,
        description="ISO currency code for the fine.",
        examples=["BDT", "THB"],
    )
    legal_consequence: str = Field(
        ...,
        description="Legal consequence beyond the monetary fine.",
        examples=["Warning issued", "Licence suspended for 30 days"],
    )

    model_config = {"from_attributes": True}  # enables ORM mode (Pydantic v2)


class TrafficLawResponse(TrafficLawBase):
    """
    Full API response model for a TrafficLaw record.
    Extends TrafficLawBase with the database primary key.
    """

    id: int = Field(..., description="Unique surrogate primary key.")

    model_config = {"from_attributes": True}


# ---------------------------------------------------------------------------
# LangChain structured output schema
# ---------------------------------------------------------------------------

class ChatbotExtraction(BaseModel):
    """
    Structured output model used by LangChain's with_structured_output()
    to extract the three key entities from the user's natural-language message.

    The LLM is forced to populate all three fields; if a field cannot be
    determined from context the LLM should make the most reasonable inference.
    """

    city: str = Field(
        ...,
        description=(
            "The city mentioned or implied in the user's message. "
            "Must be one of the supported cities (e.g., 'Dhaka', 'Bangkok'). "
            "Normalise spelling and capitalisation."
        ),
    )
    violation: str = Field(
        ...,
        description=(
            "The specific traffic violation the user is asking about. "
            "Extract the canonical violation name, e.g., 'Speeding', "
            "'Red Light', 'No Helmet', 'Wrong Way', 'No Seatbelt', etc."
        ),
    )
    vehicle_type: Literal["Two-Wheeler", "Four-Wheeler"] = Field(
        ...,
        description=(
            "The category of vehicle. "
            "Must be exactly 'Two-Wheeler' (motorcycles, scooters, bicycles) "
            "or 'Four-Wheeler' (cars, trucks, vans, buses). "
            "Infer from context when not explicitly stated."
        ),
    )


# ---------------------------------------------------------------------------
# Chat endpoint request / response schemas
# ---------------------------------------------------------------------------

class ChatRequest(BaseModel):
    """Incoming JSON body for the POST /api/chat endpoint."""

    message: str = Field(
        ...,
        min_length=1,
        description="The user's natural-language query about a traffic law or fine.",
        examples=["What is the fine for speeding on a motorcycle in Dhaka?"],
    )


class ChatResponse(BaseModel):
    """Outgoing JSON for the POST /api/chat endpoint."""

    reply: str = Field(
        ...,
        description="Conversational, natural-language answer generated by the AI.",
    )
    extracted_data: dict = Field(
        ...,
        description=(
            "The structured data extracted by LangChain from the user's message "
            "and the matching database record (or an error indicator if no record found)."
        ),
    )
